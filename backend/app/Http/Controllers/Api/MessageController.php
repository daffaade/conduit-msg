<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\Message;
use App\Models\User;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

class MessageController extends Controller
{
    /**
     * FR-02 & FR-03: Strictly return messages between authenticated user and {userId}.
     */
    public function index(Request $request, int $userId): JsonResponse
    {
        $authId = $request->user()->id;

        if ($authId === $userId) {
            return response()->json(['messages' => []]);
        }

        if (! User::whereKey($userId)->exists()) {
            return response()->json(['message' => 'Kontak tidak ditemukan.'], 404);
        }

        $messages = Message::query()
            ->where(function ($query) use ($authId, $userId) {
                $query->where('sender_id', $authId)
                    ->where('receiver_id', $userId);
            })
            ->orWhere(function ($query) use ($authId, $userId) {
                $query->where('sender_id', $userId)
                    ->where('receiver_id', $authId);
            })
            ->orderBy('sent_at')
            ->orderBy('id')
            ->get(['id', 'sender_id', 'receiver_id', 'message_text', 'sent_at']);

        return response()->json([
            'messages' => $messages,
        ]);
    }

    /**
     * FR-03 & FR-04: Store message with sent_at generated by Cloud DB CURRENT_TIMESTAMP.
     */
    public function store(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'receiver_id' => ['required', 'integer', 'exists:users,id'],
            'message_text' => ['required', 'string', 'max:5000'],
        ]);

        $authId = $request->user()->id;
        if ((int) $validated['receiver_id'] === $authId) {
            return response()->json([
                'message' => 'Tidak dapat mengirim pesan ke diri sendiri.',
            ], 422);
        }

        $id = DB::table('messages')->insertGetId([
            'sender_id' => $authId,
            'receiver_id' => (int) $validated['receiver_id'],
            'message_text' => $validated['message_text'],
            'sent_at' => DB::raw('CURRENT_TIMESTAMP'),
        ]);

        $message = Message::query()
            ->whereKey($id)
            ->first(['id', 'sender_id', 'receiver_id', 'message_text', 'sent_at']);

        return response()->json([
            'message' => $message,
        ], 201);
    }
}
